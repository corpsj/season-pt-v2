/**
 * Deterministic generator: docs/design-handoff/pt-icons.js  ->  src/components/ui/icon-data.ts
 * Extracts the PT_ICONS object literal by string-aware brace matching and re-emits it as typed TS.
 * Run: bun run scripts/gen-icons.ts
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const src = readFileSync(resolve(root, "docs/design-handoff/pt-icons.js"), "utf8");

const marker = "const PT_ICONS = {";
const start = src.indexOf(marker);
if (start === -1) throw new Error("PT_ICONS not found");
const objStart = start + marker.length - 1; // points at the opening '{'

// string-aware brace matcher
let depth = 0;
let i = objStart;
let inStr: string | null = null;
for (; i < src.length; i++) {
  const c = src[i];
  if (inStr) {
    if (c === "\\") {
      i++; // skip escaped char
      continue;
    }
    if (c === inStr) inStr = null;
    continue;
  }
  if (c === '"' || c === "'" || c === "`") {
    inStr = c;
    continue;
  }
  if (c === "{") depth++;
  else if (c === "}") {
    depth--;
    if (depth === 0) {
      i++;
      break;
    }
  }
}
const objText = src.slice(objStart, i);

// pure data literal — safe to eval
// eslint-disable-next-line no-eval
const PT_ICONS = eval("(" + objText + ")") as Record<
  string,
  { viewBox: string; body: string }
>;

const names = Object.keys(PT_ICONS).sort();
if (names.length < 70) throw new Error(`only ${names.length} icons parsed`);

const union = names.map((n) => `  | "${n}"`).join("\n");
const entries = names
  .map((n) => {
    const { viewBox, body } = PT_ICONS[n];
    return `  "${n}": { viewBox: ${JSON.stringify(viewBox)}, body: ${JSON.stringify(
      body
    )} },`;
  })
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-icons.ts — do not edit by hand.
// Source: docs/design-handoff/pt-icons.js (Wanted DS icon set, currentColor monoline).

export type IconName =
${union};

export const ICONS: Record<IconName, { viewBox: string; body: string }> = {
${entries}
};

export const ICON_NAMES = Object.keys(ICONS) as IconName[];
`;

mkdirSync(resolve(root, "src/components/ui"), { recursive: true });
writeFileSync(resolve(root, "src/components/ui/icon-data.ts"), out);
console.log(`generated icon-data.ts with ${names.length} icons`);
